/** Each sense in each official pack locale. */
export const OFFICIAL_SENSE_MESSAGES: Readonly<Record<string, SenseMessages>> =
	Object.fromEntries(
		Object.entries(OFFICIAL_SENSE_MESSAGES_BASE).map(([locale, base]) => [
			locale,
			{
				...base,
				...OFFICIAL_SENSE_MESSAGES_MORE[locale],
				...OFFICIAL_SENSE_MESSAGES_SYSTEMIC[locale],
				...OFFICIAL_SENSE_MESSAGES_R43[locale],
				...OFFICIAL_SENSE_MESSAGES_VOICE[locale],
			} as SenseMessages,
		])
	);

/** `pack` with its locale's sense translations added, when it has any. */
export function withSenseMessages(pack: LanguagePack): LanguagePack {
	const messages = OFFICIAL_SENSE_MESSAGES[pack.locale];
	return messages
		? { ...pack, messages: { ...pack.messages, ...messages } }
		: pack;
}
