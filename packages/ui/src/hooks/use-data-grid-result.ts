import type { DataGridLayoutContext } from "@ryu/ui/hooks/use-data-grid-layout.ts";
import { useMemo } from "react";

function useDataGridResult<TData>(gridContext: DataGridLayoutContext<TData>) {
	const {
		activeSearchMatch,
		adjustLayout,
		cellSelectionMap,
		columnSizeVars,
		columns,
		contextMenu,
		dataGridRef,
		dir,
		editingCell,
		enableSelectionSummary,
		fillHandleCell,
		focusedCell,
		footerRef,
		headerRef,
		measureElement,
		onRowAdd,
		pasteDialog,
		propsRef,
		rowHeight,
		rowMapRef,
		searchMatchesByRow,
		searchState,
		selectionSummary,
		table,
		tableMeta,
		virtualItems,
		virtualTotalSize,
	} = gridContext;

	return useMemo(
		() => ({
			dataGridRef,
			headerRef,
			rowMapRef,
			footerRef,
			dir,
			table,
			tableMeta,
			virtualTotalSize,
			virtualItems,
			measureElement,
			columns,
			columnSizeVars,
			searchState,
			searchMatchesByRow,
			activeSearchMatch,
			cellSelectionMap,
			focusedCell,
			editingCell,
			rowHeight,
			contextMenu,
			pasteDialog,
			onRowAdd: propsRef.current.onRowAdd ? onRowAdd : undefined,
			adjustLayout,
			fillHandleCell,
			enableSelectionSummary,
			selectionSummary,
		}),
		[
			propsRef,
			dir,
			table,
			tableMeta,
			virtualTotalSize,
			virtualItems,
			measureElement,
			columns,
			columnSizeVars,
			searchState,
			searchMatchesByRow,
			activeSearchMatch,
			cellSelectionMap,
			focusedCell,
			editingCell,
			rowHeight,
			contextMenu,
			pasteDialog,
			onRowAdd,
			adjustLayout,
			fillHandleCell,
			enableSelectionSummary,
			selectionSummary,
		]
	);
}

export { useDataGridResult };
