// `ryu-cli secrets example-env`: write the names `run` would inject as an
// example env file (`NAME=` with an empty value), for committing as
// `.env.example`. It reads the metadata list only, never the export or reveal
// routes, so no value is fetched, printed or written.
//
// The names are the live rows in the selected folder and its ancestors (the
// folders a `run` there resolves), plus every sub-folder with `--recursive`,
// narrowed by `--tags`. Sealed values are left out (`run` never injects them),
// and so are folder imports and Team and Organization values the node's list
// does not show. A description becomes a `#` comment above its name.

import { stat, writeFile } from "node:fs/promises";
import { isAbsolute, join } from "node:path";
import {
	listVaultSecrets,
	type VaultSecret,
	vaultValueType,
} from "@ryuhq/core-client/vault";
import { tf } from "../i18n/translate.ts";
import { flag, type SecretsArgs } from "./secrets-args.ts";
import { printJson } from "./secrets-output.ts";
import { tagFilter } from "./secrets-project.ts";
import {
	isBelow,
	normalizeFolder,
	RECURSIVE_FLAG,
} from "./secrets-recursive.ts";
import { namesWithTags } from "./secrets-run-env.ts";
import { type CliContext, UsageError } from "./types.ts";

const HEADER =
	"# Generated by `ryu-cli secrets example-env`. Names only: fill in values locally and never commit them.";

/** Whether `path` is `root` or one of its ancestors. */
function inChain(path: string, root: string): boolean {
	const folder = normalizeFolder(path);
	return folder === root || folder === "/" || root.startsWith(`${folder}/`);
}

export interface ExampleEntry {
	description: string;
	name: string;
}

/** The example entries for `rows`, sorted by name. */
export function exampleEntries(
	rows: VaultSecret[],
	root: string,
	recursive: boolean,
	tags: string[]
): ExampleEntry[] {
	const live = rows.filter(
		(row) =>
			row.status !== "deleted" &&
			vaultValueType(row.metadata) !== "sealed" &&
			(inChain(row.path, root) || (recursive && isBelow(row.path, root)))
	);
	const allowed = tags.length > 0 ? new Set(namesWithTags(live, tags)) : null;
	const entries = new Map<string, string>();
	for (const row of live) {
		if (allowed && !allowed.has(row.name)) {
			continue;
		}
		const known = entries.get(row.name);
		if (!known) {
			entries.set(row.name, row.metadata.description.trim());
		}
	}
	return [...entries]
		.sort(([a], [b]) => (a < b ? -1 : Number(a > b)))
		.map(([name, description]) => ({ name, description }));
}

/** Render entries as dotenv text with empty values. */
export function renderExample(entries: ExampleEntry[]): string {
	const lines = [HEADER];
	for (const entry of entries) {
		if (entry.description) {
			lines.push(`# ${entry.description.replace(/\s*\r?\n\s*/g, " ")}`);
		}
		lines.push(`${entry.name}=`);
	}
	return `${lines.join("\n")}\n`;
}

async function exists(path: string): Promise<boolean> {
	try {
		await stat(path);
		return true;
	} catch {
		return false;
	}
}

export async function exampleEnv(
	ctx: CliContext,
	args: SecretsArgs
): Promise<number> {
	const root = normalizeFolder(flag(args, "--path"));
	const recursive = args.booleans.has(RECURSIVE_FLAG);
	// The whole environment, so the ancestors of `root` are included too.
	const { secrets } = await listVaultSecrets(ctx.target, {
		environment: flag(args, "--env"),
		recursive: true,
	});
	const entries = exampleEntries(secrets, root, recursive, tagFilter(args));
	if (ctx.flags.json) {
		printJson(ctx, { names: entries.map((entry) => entry.name) });
		return 0;
	}
	const text = renderExample(entries);
	const out = flag(args, "--out");
	if (out === undefined) {
		ctx.io.out(text);
		return 0;
	}
	const cwd = ctx.cwd ?? process.cwd();
	const path = isAbsolute(out) ? out : join(cwd, out);
	if (!ctx.flags.force && (await exists(path))) {
		throw new UsageError(
			tf("{file} already exists; pass --force to replace it.", { file: out })
		);
	}
	await writeFile(path, text, "utf8");
	ctx.io.out(
		`${tf("Wrote {count, plural, one {# name} other {# names}} to {file}.", { count: entries.length, file: out })}\n`
	);
	return 0;
}
