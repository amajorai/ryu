//! Shared downloader for the Ghost and Shadow satellite binaries.
//!
//! Each engine's `downloader.rs` keeps its release repo, override env, asset name
//! and install path in a [`SatelliteBinary`]; everything else (URL resolution,
//! checksum verification, extraction, atomic install) lives here once.

use std::path::PathBuf;

use anyhow::{Context, Result};

use crate::sidecar::download_manager::{
    build_http_client, compute_sha256, extract_from_tar_gz, extract_from_zip, fetch_sibling_sha256,
    sha256_sibling_url, ProgressCallback, VersionStore,
};

// ── Release URL ────────────────────────────────────────────────────────────────
//
// WHERE A SATELLITE BINARY ON A USER MACHINE COMES FROM.
//
// 1. The satellite release at github.com/amajorai/<bin> owns the binary. The
//    read-only mirror generated by tools/mirror-satellites.sh (legacy group)
//    carries the complete source closure, guarded at mirror time (the published
//    tree once omitted `crates/ghost/permissions` and `cargo metadata` died in it),
//    plus a dispatch-only release workflow that builds Linux, macOS and Windows
//    archives at the train tag and a sibling .sha256 for each. The hub release
//    (github.com/amajorai/ryu) neither builds nor mirrors these archives.
//
// 2. The matrix is `crate::sidecar::tools::SATELLITE_ARCHIVE_PLATFORMS`; a host
//    outside it is refused before any network I/O with an error naming its
//    platform and the override, rather than a bare 404. `releases/latest/download`
//    (not a pinned tag) mirrors `manifest_sidecar`: an older Core pulls the newest
//    binary, normally the same train version anyway.
//
// 3. `RYU_<BIN>_RELEASE_URL` overrides it with a FULL per-platform URL (not a base
//    like `RYU_SIDECAR_RELEASE_BASE`): a private, pre-release, self-hosted or
//    locally-built archive, including for a platform the matrix does not cover.
//
// The asset name (`<bin>-<os>-<arch>.<ext>`) is DERIVED from
// [`crate::update::platform_tag`] in each engine's `artifact_name`, so it cannot
// drift from the slug the release workflow stages assets under. Its extension is
// load-bearing: `ensure_installed` downloads an ARCHIVE and extracts the binary.
//
// ── Archive integrity: the sibling `.sha256` ───────────────────────────────────
//
// `ensure_installed` verifies the downloaded archive against the release's
// sibling `<asset>.sha256`: a published digest nothing verifies against cannot
// take effect, and this is a binary Ryu then *runs*. The parser and fetcher live
// in `download_manager` (shared with the mesh downloader).
// `manifest_sidecar::fetch_release_sha256` stays separate: it is
// `#[cfg(not(debug_assertions))]` and its `screen_https` SSRF screen is private.

/// One satellite binary's release coordinates and install details.
pub(super) struct SatelliteBinary {
    /// Lower-case binary name: the VersionStore key, log prefix and archive member.
    pub(super) name: &'static str,
    /// Display name used in the download label and error text.
    pub(super) label: &'static str,
    /// `owner/repo` of the satellite release.
    pub(super) repo: &'static str,
    /// Env knob carrying the FULL per-platform release archive URL.
    pub(super) url_env: &'static str,
    /// File stem of the temp archive the download center writes.
    pub(super) tmp_stem: &'static str,
    /// Arguments that make the installed binary print its version.
    pub(super) version_args: &'static [&'static str],
    /// Where the extracted binary is installed.
    pub(super) bin_path: fn() -> PathBuf,
    /// The release asset this host needs (`<bin>-<os>-<arch>.<ext>`).
    pub(super) artifact_name: fn() -> String,
}

impl SatelliteBinary {
    /// The trimmed, non-blank value of [`Self::url_env`], if set.
    fn release_url_override(&self) -> Option<String> {
        std::env::var(self.url_env)
            .ok()
            .map(|url| url.trim().to_owned())
            .filter(|url| !url.is_empty())
    }

    /// `Some(reason)` when this host has no published satellite archive and no
    /// override points at one — checked before any network I/O, so an unsupported
    /// platform reads as itself rather than as a missing checksum or a 404.
    fn unpublished_platform_error(&self) -> Option<String> {
        if self.release_url_override().is_some() {
            return None;
        }
        super::unpublished_satellite_platform(
            self.name,
            self.repo,
            self.url_env,
            &crate::update::platform_tag(),
        )
    }

    /// Resolve the release archive URL for this platform: the override verbatim
    /// when set and non-blank, otherwise the satellite release asset.
    ///
    /// **Infallible on purpose.** This used to return `Err` when the env was unset,
    /// because the release train had no public release owner. The satellite now
    /// owns the archive, so refusing to synthesize the URL would leave a published
    /// artifact unreachable. The remaining unpublished-platform case is diagnosed
    /// where the 404 actually surfaces, in [`SatelliteDownloader::ensure_installed`].
    fn archive_url(&self) -> String {
        if let Some(url) = self.release_url_override() {
            return url;
        }
        format!(
            "https://github.com/{}/releases/latest/download/{}",
            self.repo,
            (self.artifact_name)()
        )
    }
}

pub(super) struct SatelliteDownloader {
    spec: &'static SatelliteBinary,
    client: reqwest::Client,
    on_progress: Option<ProgressCallback>,
}

impl SatelliteDownloader {
    pub(super) fn new(spec: &'static SatelliteBinary) -> Self {
        Self {
            spec,
            client: build_http_client(),
            on_progress: None,
        }
    }

    pub(super) fn with_progress(mut self, cb: ProgressCallback) -> Self {
        self.on_progress = Some(cb);
        self
    }

    /// The archive's sibling `<url>.sha256`, or `None` when absent, unreachable or
    /// malformed. Only `https` URLs are followed: over plaintext, whoever rewrote
    /// the archive could rewrite its checksum too.
    async fn fetch_release_sha256(&self, archive_url: &str) -> Option<String> {
        fetch_sibling_sha256(&self.client, archive_url).await
    }

    /// Ensure the binary is installed at the spec's `bin_path`.
    ///
    /// The GitHub release archive downloads through the global
    /// [`DownloadCenter`](crate::downloads::DownloadCenter) (#456) so it streams to
    /// disk and shows in the overlay; we then extract the binary from the
    /// downloaded archive and place it atomically.
    pub(super) async fn ensure_installed(
        &self,
        downloads: &crate::downloads::DownloadCenter,
    ) -> Result<()> {
        let spec = self.spec;
        let name = spec.name;
        let label = spec.label;
        let dest = (spec.bin_path)();

        // Fast path: already installed with a matching checksum.
        let store = VersionStore::load();
        if dest.exists() {
            if let Some(stored) = store.installed_checksum(name) {
                let actual = compute_sha256(&dest).await?;
                if actual == stored {
                    tracing::info!("{name} already installed and checksum valid — skipping");
                    return Ok(());
                }
                tracing::warn!(
                    "{name} checksum mismatch (stored={stored} actual={actual}), re-downloading"
                );
            }
        }

        if let Some(reason) = spec.unpublished_platform_error() {
            anyhow::bail!(reason);
        }
        let url = spec.archive_url();
        tracing::info!("downloading {name} binary from {url}");

        // Download the archive through the center to a deterministic temp dest
        // (so its own `.part`/resume works), then read it back to extract. The
        // archive extension matches the platform's release artifact.
        let archive_ext = if cfg!(target_os = "windows") {
            "zip"
        } else {
            "tar.gz"
        };
        let archive_dest = crate::sidecar::download_manager::tmp_dir()
            .join(format!("{}.{archive_ext}", spec.tmp_stem));

        // Integrity: verify the ARCHIVE against the sibling `.sha256` the release
        // publishes. Note the scope — this digest covers the downloaded archive
        // (`DownloadSpec::dest`), NOT the binary extracted from it, which is hashed
        // separately below and recorded in `versions.json` under the `name` key.
        // The two are different values over different bytes; feeding either into
        // the other's comparison would invert the fast path.
        let sha256 = self.fetch_release_sha256(&url).await.ok_or_else(|| {
            anyhow::anyhow!(
                "{name} archive has no trusted sibling checksum at {}; refusing to install. \
                 If that URL is a 404, the {label} satellite release has not published `{}` \
                 yet (dispatch its release workflow at the train tag)",
                sha256_sibling_url(&url),
                (spec.artifact_name)()
            )
        })?;

        let archive_path = downloads
            .download_blocking(crate::downloads::DownloadSpec {
                kind: crate::downloads::DownloadKind::Tool,
                role: crate::downloads::DownloadRole::Tool,
                label: label.to_string(),
                url: url.to_string(),
                dest: archive_dest,
                sha256: Some(sha256),
                version_record: None,
            })
            .await
            // Name the likely cause at the point where a missing platform asset
            // becomes an HTTP 404, rather than leaving a bare transfer error.
            .with_context(|| {
                format!(
                    "downloading {name} archive from {url}. If this is a 404, the \
                     {label} satellite publishes no `{}` — set {} to a \
                     self-built or pre-release archive for this platform, or build \
                     {name} from source (apps/{name} in the monorepo, or its public \
                     mirror github.com/amajorai/{name})",
                    (spec.artifact_name)(),
                    spec.url_env
                )
            })?;
        let archive_data = tokio::fs::read(&archive_path)
            .await
            .with_context(|| format!("reading downloaded {name} archive"))?;

        // Extract binary from the archive (blocking I/O on a thread-pool thread).
        let binary_name = if cfg!(target_os = "windows") {
            format!("{name}.exe")
        } else {
            name.to_owned()
        };
        let extracted = tokio::task::spawn_blocking(move || {
            #[cfg(target_os = "windows")]
            {
                extract_from_zip(&archive_data, &binary_name)
            }
            #[cfg(not(target_os = "windows"))]
            {
                extract_from_tar_gz(&archive_data, &binary_name)
            }
        })
        .await
        .context("spawn_blocking for archive extraction")??;

        // Write extracted binary atomically.
        if let Some(parent) = dest.parent() {
            tokio::fs::create_dir_all(parent).await?;
        }
        let atomic_tmp = dest.with_extension("tmp");
        tokio::fs::write(&atomic_tmp, &extracted)
            .await
            .with_context(|| format!("writing {}", atomic_tmp.display()))?;
        tokio::fs::rename(&atomic_tmp, &dest)
            .await
            .with_context(|| format!("rename {} → {}", atomic_tmp.display(), dest.display()))?;

        // Set executable bit on Unix.
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = std::fs::metadata(&dest)?.permissions();
            perms.set_mode(0o755);
            std::fs::set_permissions(&dest, perms)?;
        }

        // Compute checksum from in-memory bytes (avoids re-reading from disk).
        let checksum = {
            use sha2::{Digest, Sha256};
            let mut hasher = Sha256::new();
            hasher.update(&extracted);
            hex::encode(hasher.finalize())
        };
        let version = super::probe_tool_version(&dest, spec.version_args).await;
        VersionStore::record_persisted(name, &version, &checksum)
            .context("writing versions.json")?;

        // The extracted binary is in place; drop the temp archive.
        let _ = tokio::fs::remove_file(&archive_path).await;

        // Ensure PATH includes ~/.ryu/bin
        if let Err(e) = crate::sidecar::path_manager::PathManager::add_to_path() {
            tracing::warn!("Failed to add ~/.ryu/bin to PATH: {}", e);
        }

        tracing::info!("{name} installed at {}", dest.display());
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SPECS: [&SatelliteBinary; 2] = [
        &super::super::ghost::downloader::SPEC,
        &super::super::shadow::downloader::SPEC,
    ];

    // `std::env::set_var` is process-global: these tests must not interleave with
    // each other, across both specs.
    static ENV_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
    fn lock_env() -> std::sync::MutexGuard<'static, ()> {
        ENV_LOCK.lock().unwrap_or_else(|e| e.into_inner())
    }

    struct EnvGuard {
        var: &'static str,
        prev: Option<String>,
    }
    impl EnvGuard {
        fn set(spec: &SatelliteBinary, val: &str) -> Self {
            let prev = std::env::var(spec.url_env).ok();
            std::env::set_var(spec.url_env, val);
            Self {
                var: spec.url_env,
                prev,
            }
        }
        fn clear(spec: &SatelliteBinary) -> Self {
            let prev = std::env::var(spec.url_env).ok();
            std::env::remove_var(spec.url_env);
            Self {
                var: spec.url_env,
                prev,
            }
        }
    }
    impl Drop for EnvGuard {
        fn drop(&mut self) {
            match &self.prev {
                Some(v) => std::env::set_var(self.var, v),
                None => std::env::remove_var(self.var),
            }
        }
    }

    #[test]
    fn artifact_name_uses_the_release_trains_platform_slug() {
        // The whole point of deriving the name: it cannot drift from the slug the
        // release workflow stages assets under. Asserting against a literal is what
        // let `macos-arm64` survive next to a train that publishes `macos-aarch64`.
        for spec in SPECS {
            let name = (spec.artifact_name)();
            assert!(name.starts_with(&format!("{}-", spec.name)), "got: {name}");
            assert!(
                name.contains(&crate::update::platform_tag()),
                "artifact name {name} must carry the release train's platform slug {}",
                crate::update::platform_tag()
            );
            // An ARCHIVE, because `ensure_installed` extracts a binary out of it.
            let ext = if cfg!(target_os = "windows") {
                ".zip"
            } else {
                ".tar.gz"
            };
            assert!(name.ends_with(ext), "got: {name}");
        }
    }

    #[test]
    fn archive_url_defaults_to_the_satellite_release_asset() {
        // The satellite owns the platform archives; the hub release does not.
        let _lock = lock_env();
        for spec in SPECS {
            let _g = EnvGuard::clear(spec);
            let url = spec.archive_url();
            assert_eq!(
                url,
                format!(
                    "https://github.com/{}/releases/latest/download/{}",
                    spec.repo,
                    (spec.artifact_name)()
                ),
                "got: {url}"
            );
            assert!(url.ends_with(&(spec.artifact_name)()), "got: {url}");
            // `latest`, not a pinned tag — mirrors `manifest_sidecar`.
            assert!(url.contains("/releases/latest/download/"), "got: {url}");
        }
    }

    #[test]
    fn unpublished_platform_check_follows_the_published_list_and_the_override() {
        let _lock = lock_env();
        let published = crate::sidecar::tools::SATELLITE_ARCHIVE_PLATFORMS
            .contains(&crate::update::platform_tag().as_str());
        for spec in SPECS {
            {
                let _g = EnvGuard::clear(spec);
                assert_eq!(spec.unpublished_platform_error().is_none(), published);
            }
            // The override exists for unpublished platforms, so it always
            // suppresses the refusal.
            let _g = EnvGuard::set(spec, "https://mirror.test/bin.tar.gz");
            assert_eq!(spec.unpublished_platform_error(), None);
        }
    }

    #[test]
    fn archive_url_uses_env_override_trimmed() {
        // The override wins over the default and is used VERBATIM: it carries a
        // full URL, not a base to append `artifact_name()` to.
        let _lock = lock_env();
        for spec in SPECS {
            let _g = EnvGuard::set(spec, "  https://mirror.test/bin.tar.gz  ");
            assert_eq!(spec.archive_url(), "https://mirror.test/bin.tar.gz");
        }
    }

    #[test]
    fn archive_url_blank_env_falls_back_to_the_satellite_default() {
        // A blank/whitespace value is unset, not an empty URL.
        let _lock = lock_env();
        for spec in SPECS {
            let _g = EnvGuard::set(spec, "   ");
            assert!(spec.archive_url().starts_with("https://github.com/"));
            assert!(spec.archive_url().ends_with(&(spec.artifact_name)()));
        }
    }

    // ── sibling `.sha256` ─────────────────────────────────────────────────────
    //
    // The PARSER's tests live in `download_manager::sha256_sibling_tests`. What
    // stays here is satellite-specific: that the URL we actually request is the
    // sibling of the archive URL we synthesize, and that the wrapper keeps the
    // https-only rule.

    #[test]
    fn sha256_url_is_the_published_asset_plus_the_suffix() {
        // The release workflow emits `<asset>.sha256` — an exact sibling, not a
        // separate SHASUMS manifest. If this ever drifts, every download silently
        // falls back to unverified, so pin it against the URL we really request.
        let _lock = lock_env();
        for spec in SPECS {
            let _g = EnvGuard::clear(spec);
            let url = spec.archive_url();
            assert_eq!(sha256_sibling_url(&url), format!("{url}.sha256"));
            assert!(
                sha256_sibling_url(&url).ends_with(".tar.gz.sha256") || cfg!(target_os = "windows")
            );
        }
    }

    #[tokio::test]
    async fn fetch_release_sha256_refuses_non_https_urls() {
        // The override is operator input. Over plaintext the checksum is rewritable
        // by whoever rewrote the archive, so we decline rather than perform
        // verification theatre. No network is touched here: the scheme check
        // returns before any request is built.
        for spec in SPECS {
            let d = SatelliteDownloader::new(spec);
            assert_eq!(
                d.fetch_release_sha256("http://mirror.test/b.tar.gz").await,
                None
            );
            assert_eq!(d.fetch_release_sha256("file:///tmp/b.tar.gz").await, None);
            assert_eq!(d.fetch_release_sha256("/tmp/b.tar.gz").await, None);
        }
    }
}
